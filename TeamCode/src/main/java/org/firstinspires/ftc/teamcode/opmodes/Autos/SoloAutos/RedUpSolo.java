package org.firstinspires.ftc.teamcode.opmodes.Autos.SoloAutos;

import static com.pedropathing.ivy.commands.Commands.waitMs;
import static com.pedropathing.ivy.groups.Groups.sequential;
import static org.firstinspires.ftc.teamcode.navmodel.ModelMoveCommands.driveTo;
import static org.firstinspires.ftc.teamcode.navmodel.ModelMoveCommands.instant;
import static org.firstinspires.ftc.teamcode.navmodel.ModelMoveCommands.sleepAndHold;
import static org.firstinspires.ftc.teamcode.navmodel.ModelMoveCommands.via;
import static org.firstinspires.ftc.teamcode.navmodel.ModelMoveCommands.at;

import com.pedropathing.ivy.Scheduler;
import com.qualcomm.robotcore.eventloop.opmode.Autonomous;
import com.qualcomm.robotcore.eventloop.opmode.LinearOpMode;

import org.firstinspires.ftc.teamcode.navmodel.ModelMove;
import org.firstinspires.ftc.teamcode.subsystems.Intake;
import org.firstinspires.ftc.teamcode.subsystems.Shooter;
import org.firstinspires.ftc.teamcode.subsystems.ShooterGate;
import org.firstinspires.ftc.teamcode.subsystems.FlowerRobber;

/** Generated by the route planner (tools/path_demo/planner.html): 6 moves, 4 intermediate points, red alliance. */
@Autonomous(name = "RedUpSolo", group = "Autonomous")
public class RedUpSolo extends LinearOpMode {
    @Override
    public void runOpMode() {
        Scheduler.reset();
        ModelMove move = new ModelMove(this, 56.5, 8.05, 180);   // the robot stands here, still, at init
        Intake intake = new Intake();
        intake.init(hardwareMap);
        Shooter shooter = new Shooter();
        shooter.initialize(hardwareMap);
        ShooterGate gate = new ShooterGate();
        gate.init(hardwareMap);                                   // closed; nothing calls gate.updateLoop(), so it stays as set
        FlowerRobber robber = new FlowerRobber();
        robber.init(hardwareMap);                                 // up
        waitForStart();

        Scheduler.schedule(sequential(
                instant(() -> { intake.setFORWARD(); shooter.setVel(2100); gate.open(); }), // at start
                waitMs(2000),
                driveTo(move, 12.46, 8.24, 180, via(41, 8.05, 10), via(26, 8.05, 10)), // 1
                waitMs(700),
                driveTo(move, 48.5, 119, 90, via(33, 101, 10), at(0.75, () -> robber.setDOWN())), // 2
                instant(() -> gate.open()),                     // at 2
                waitMs(2000),
                driveTo(move, 48.6, 126.6, 90),                 // 3
                waitMs(2000),
                instant(() -> gate.close()),                    // leaving 3
                driveTo(move, 17.4, 48.6, 180, via(28.5, 92, 10)), // 4
                waitMs(2000),
                driveTo(move, 54.5, 15.5, 90, at(0.4, () -> robber.setUP())), // 5
                instant(() -> gate.open()),                     // at 5
                sleepAndHold(move, 2000),
                instant(() -> { intake.setSTOP(); shooter.setVel(0); }), // leaving 5
                driveTo(move, 14.5, 92, 90)));                  // 6

        while (opModeIsActive()) {
            Scheduler.execute();
            move.addTelemetry();
            telemetry.update();
        }
    }
}

