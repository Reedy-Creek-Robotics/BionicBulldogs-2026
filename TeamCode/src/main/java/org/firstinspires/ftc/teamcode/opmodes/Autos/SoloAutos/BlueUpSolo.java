import com.pedropathing.ivy.Scheduler;
import com.qualcomm.robotcore.eventloop.opmode.Autonomous;
import com.qualcomm.robotcore.eventloop.opmode.LinearOpMode;

import org.firstinspires.ftc.teamcode.navmodel.ModelMove;
import org.firstinspires.ftc.teamcode.subsystems.Intake;
import org.firstinspires.ftc.teamcode.subsystems.Shooter;
import org.firstinspires.ftc.teamcode.subsystems.ShooterGate;
import org.firstinspires.ftc.teamcode.subsystems.FlowerRobber;

/** Generated by the route planner (tools/path_demo/planner.html): 6 moves, 4 intermediate points, blue alliance. */
@Autonomous(name = "BlueUpSolo", group = "Autonomous")
public class BlueUpSolo extends LinearOpMode {
    @Override
    public void runOpMode() {
        Scheduler.reset();
        ModelMove move = new ModelMove(this, 87.5, 135.95, 0);   // the robot stands here, still, at init
        Intake intake = new Intake();
        intake.init(hardwareMap);
        Shooter shooter = new Shooter();
        shooter.initialize(hardwareMap);
        ShooterGate gate = new ShooterGate();
        gate.init(hardwareMap);                                   // closed; nothing calls gate.updateLoop(), so it stays as set
        FlowerRobber robber = new FlowerRobber();
        robber.init(hardwareMap);                                 // up
        waitForStart();

        Scheduler.schedule(sequential(
                instant(() -> { intake.setFORWARD(); shooter.setVel(2100); gate.open(); }), // at start
                waitMs(2000),
                driveTo(move, 131.54, 135.76, 0, via(103, 135.95, 10), via(118, 135.95, 10)), // 1
                waitMs(700),
                driveTo(move, 95.5, 25, 270, via(111, 43, 10), at(0.75, () -> robber.setDOWN())), // 2
                instant(() -> gate.open()),                     // at 2
                waitMs(2000),
                driveTo(move, 95.4, 17.4, 270),                 // 3
                waitMs(2000),
                instant(() -> gate.close()),                    // leaving 3
                driveTo(move, 126.6, 95.4, 0, via(115.5, 52, 10)), // 4
                waitMs(2000),
                driveTo(move, 89.5, 128.5, 270, at(0.4, () -> robber.setUP())), // 5
                instant(() -> gate.open()),                     // at 5
                sleepAndHold(move, 2000),
                instant(() -> { intake.setSTOP(); shooter.setVel(0); }), // leaving 5
                driveTo(move, 129.5, 52, 270)));                // 6

        while (opModeIsActive()) {
            Scheduler.execute();
            move.addTelemetry();
            telemetry.update();
        }
    }
}
